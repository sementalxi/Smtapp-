// Shared (client + server) definitions for banner templates and inputs.

export type LayoutKind = "PLAYER" | "CHAMPIONS" | "EVENT" | "MATCHDAY" | "LINEUP" | "RESULT" | "STANDINGS" | "LOGO" | "TOTW" | "QUALIFIERS" | "WINNERS";

export type FontKey = "anton" | "bebas" | "gothic" | "brush" | "sans";
export type Particles = "sparks" | "embers" | "snow" | "none";

export interface TemplateStyle {
  primary: string; // main brand color of the template
  accent: string; // highlight / glow color
  dark: string; // deep shadow color
  nameFont: FontKey;
  scriptFont: FontKey;
  /** Top → bottom gradient used for the big name / title */
  nameGradient: string[];
  /** Gradient used when no AI background exists (also used for previews) */
  fallback: string[];
  particles: Particles;
  ghost: boolean; // big faded portrait behind the player
  giantText: boolean; // huge outlined team name in the background
  streaks: boolean; // diagonal light streaks
}

export interface BannerInputs {
  name: string; // player / gamertag
  team: string;
  position: string; // "CAM | OM", "DFC", "CB"
  number: string;
  tagline: string; // small text above the name ("WELCOME", "MVP")
  subtitle: string; // script text under the name
  footer: string; // spaced letters at the bottom ("LIGA X EDITION")
  headline: string; // EVENT/CHAMPIONS big word ("CHAMPIONS", "$100")
  eventName: string; // "LPL WINNERS"
  roster: string[]; // CHAMPIONS
  prize: string; // "$200 PRIZE"
  date: string; // EVENT
  details: string; // EVENT ("8 PM · 9 PM · 10 PM")
  rule: string; // EVENT: a rule / requirement in its own box ("GIANTS ONLY")
  ruleNote: string; // EVENT: the small line under the rule ("MUST BE MAX HEIGHT AND MAX WEIGHT")
  entry: string; // EVENT: the entry fee box ("$10 ENTRY", "FREE ENTRY")
  regions: string[]; // QUALIFIERS: one row per region — "🇪🇺 Europe · 24"
  unit: string; // QUALIFIERS: what the numbers count ("Managers", "Teams")
  total: string; // QUALIFIERS: the total bar (empty = computed from the rows)
  winners: string[]; // WINNERS: the winning teams in order — one per box ("Ackerman")
  winnerLogos: string[]; // WINNERS: crest per winner (matched from the saved teams; "" = none)
  boxes: string; // WINNERS: how many frames the showcase has ("15")
  extraPrompt: string; // added to the AI background prompt
  // Match day / lineup / result
  homeTeam: string;
  awayTeam: string;
  homeScore: string;
  awayScore: string;
  competition: string;
  venue: string;
  time: string;
  formation: string; // "4-3-3"
  players: string[]; // lineup: "10 Name ST"
  scorers: string[]; // result
  standings: string[]; // standings table rows
  fixtures: string[]; // STANDINGS layout used as a fixtures list: "Home vs Away · 20:00" per row (crests in tableLogos, 2 per row)
  qualify: string; // standings: how many top rows advance / qualify ("" = none)
  relegate: string; // standings: how many bottom rows are out / relegated ("" = none)
  tableLogos: string[]; // standings: crest URL per row ("" = none)
  playerPhotos: string[]; // team of the week: photo URL per player line ("" = none)
  playerLogos: string[]; // team of the week: club crest URL per player line ("" = none)
  partnerLogos: string[]; // event: collaborator / co-organizer logos (up to 4)
  partnerNames: string[]; // event: their names, same order
  photo2Url: string; // PLAYER: a second photo of the same player, used for the background figure
  slots: Record<string, string>; // PLAYER flyer styles: one text per flyer line (lib/text-slots)
  refImageUrl: string; // the user's inspiration image: a style reference only (look, not content)
  trophy: string; // champions trophy style
  colorMode: string; // "surprise" | "template" | "custom"
  color1: string;
  color2: string;
  aiCopy: string; // "on" lets the AI add a couple of hype words
  aiLogo: string; // "both" = 3D remake + real file pasted (admins); "" / "exact" = the AI places the real crest faithfully (default); "on" = 3D remake; "off" = the file is pasted in a corner
  bgPose: string;
  bgScene: string; // background scene id, "" = surprise // player card: pose of the second, AI-made figure in the background
  // Typography (Pro AI)
  language: string; // language for generic words on the poster
  fontPrimary: string; // titles
  fontSecondary: string; // names, numbers
  // Extra reference images (our own storage URLs)
  homeLogoUrl: string;
  awayLogoUrl: string;
  champLogoUrl: string;
  trophyUrl: string;
}

